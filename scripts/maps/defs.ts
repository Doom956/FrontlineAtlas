// The real-world maps: frame, projection, size target and nation spawns. Spawn cities are looked up by name in
// Natural Earth's populated places (ne_10m_populated_places_simple), so their coordinates come from the data set;
// `country` narrows the lookup when a city name exists in several countries.
import type { LonLatBox, ProjDef } from './lib';

export interface SpawnDef {
  /** nation name shown in the game */
  name: string;
  /** Natural Earth populated place (name, nameascii or namealt) */
  city: string;
  /** Natural Earth adm0name, to disambiguate */
  country?: string;
  /** a major power: comes early in the spawn order (among the spawns far enough from those before it) */
  major?: boolean;
}

export interface MapDef {
  id: string;
  name: string;
  description: string;
  proj: ProjDef;
  frame: LonLatBox;
  /** optional lon/lat points whose projected bounding box is the map (instead of the frame's outline) */
  fit?: number[][];
  /** target land tiles (the scale is chosen for it, within 2600 x 1600) */
  targetLand: number;
  isWorld?: boolean;
  /** cap on the forest share of plains + forest land (default 0.48; Britain is mostly farmland) */
  forestMax?: number;
  /** listed in any order: the build sorts them so any first N are spread out (see spreadOrder in build.ts) */
  spawns: SpawnDef[];
}

const s = (name: string, city: string, country?: string): SpawnDef => ({ name, city, country });
/** a major power (see SpawnDef.major) */
const m = (name: string, city: string, country?: string): SpawnDef => ({ name, city, country, major: true });

